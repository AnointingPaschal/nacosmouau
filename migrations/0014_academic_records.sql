-- Academic records: course catalogue, course registration and results (GPA / CGPA are computed in the app).
CREATE TABLE IF NOT EXISTS course_catalogue(
  id TEXT PRIMARY KEY,
  code TEXT NOT NULL,
  title TEXT NOT NULL,
  units INTEGER NOT NULL CHECK(units BETWEEN 0 AND 20),
  level TEXT NOT NULL,
  semester INTEGER NOT NULL CHECK(semester IN (1,2)),
  category TEXT NOT NULL DEFAULT 'mandatory',
  owner_user_id TEXT,
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_course_catalogue_level ON course_catalogue(level, semester, code);
CREATE INDEX IF NOT EXISTS idx_course_catalogue_owner ON course_catalogue(owner_user_id);

CREATE TABLE IF NOT EXISTS member_courses(
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  course_id TEXT NOT NULL,
  session TEXT NOT NULL,
  level TEXT NOT NULL,
  semester INTEGER NOT NULL CHECK(semester IN (1,2)),
  score REAL CHECK(score IS NULL OR (score >= 0 AND score <= 100)),
  grade TEXT CHECK(grade IS NULL OR grade IN ('A','B','C','D','E','F')),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE(user_id, course_id, session)
);
CREATE INDEX IF NOT EXISTS idx_member_courses_user ON member_courses(user_id, session, semester);

